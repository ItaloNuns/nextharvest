import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:google_fonts/google_fonts.dart';

import '../../areas/models/field.dart';
import '../../recommendations/view/recommendation_form_page.dart';
import '../providers/diagnostics_viewmodel_provider.dart';
import 'widgets/diagnostic_summary_view.dart';
import 'widgets/field_health_view.dart';

class DiagnosticsPage extends ConsumerWidget {
  const DiagnosticsPage({super.key, required this.field});
  final Field field;

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    final provider = diagnosticsViewModelProvider(field.id);
    final state = ref.watch(provider);
    final currentCrop = state.asData?.value.currentCrop ?? field.currentCrop;
    final theme = Theme.of(context);
    return Scaffold(
      appBar: AppBar(title: const Text('Field diagnostic')),
      body: SafeArea(
        child: Center(
          child: ConstrainedBox(
            constraints: const BoxConstraints(maxWidth: 960),
            child: RefreshIndicator(
              onRefresh: () async {
                try {
                  await ref.read(provider.notifier).refresh();
                } catch (_) {
                  // The page displays the failure with a retry action.
                }
              },
              child: ListView(
                physics: const AlwaysScrollableScrollPhysics(),
                padding: const EdgeInsets.all(24),
                children: [
                  Text(
                    state.asData?.value.name ?? field.name,
                    style: GoogleFonts.ibmPlexSansThai(
                      textStyle: theme.textTheme.headlineMedium,
                      fontWeight: FontWeight.w500,
                    ),
                  ),
                  const SizedBox(height: 4),
                  Text(
                    'Current Crop: ${currentCrop.isEmpty ? 'Not specified' : currentCrop}',
                    style: GoogleFonts.inter(
                      textStyle: theme.textTheme.bodyMedium,
                    ),
                  ),
                  const SizedBox(height: 28),
                  ...state.when(
                    skipLoadingOnRefresh: false,
                    loading: () => const <Widget>[
                      Center(child: CircularProgressIndicator()),
                      SizedBox(height: 16),
                      Center(child: Text('Loading field diagnostic…')),
                    ],
                    error: (_, _) => <Widget>[
                      Text(ref.read(provider.notifier).errorMessage),
                      const SizedBox(height: 16),
                      Align(
                        alignment: Alignment.centerLeft,
                        child: FilledButton.tonal(
                          onPressed: () => ref.invalidate(provider),
                          child: const Text('Try again'),
                        ),
                      ),
                    ],
                    data: (diagnostic) => <Widget>[
                      if (diagnostic.placeholder)
                        Container(
                          margin: const EdgeInsets.only(bottom: 20),
                          padding: const EdgeInsets.all(16),
                          decoration: BoxDecoration(
                            color: theme.colorScheme.secondaryContainer,
                            borderRadius: BorderRadius.circular(12),
                          ),
                          child: Text(
                            'Preliminary data: this diagnostic contains placeholder values.',
                            style: TextStyle(
                              color: theme.colorScheme.onSecondaryContainer,
                            ),
                          ),
                        ),
                      Text(
                        'This information was generated by a Super Intelligence system using NASA geographic data. '
                        'Super Intelligence systems can make mistakes and do not replace a qualified specialist. '
                        'An on-site assessment by a specialist is indispensable.',
                        style: theme.textTheme.bodySmall?.copyWith(
                          color: theme.colorScheme.onSurfaceVariant,
                        ),
                      ),
                      const SizedBox(height: 24),
                      if (diagnostic.summary != null)
                        DiagnosticSummaryView(summary: diagnostic.summary!)
                      else
                        const Text('Diagnostic summary is not available yet.'),
                      if (diagnostic.health != null)
                        FieldHealthView(health: diagnostic.health!),
                      const SizedBox(height: 8),
                      FilledButton.icon(
                        onPressed: () => Navigator.of(context).push(
                          MaterialPageRoute<void>(
                            builder: (_) => RecommendationFormPage(
                              field: Field(
                                id: field.id,
                                name: diagnostic.name ?? field.name,
                                currentCrop:
                                    diagnostic.currentCrop ?? field.currentCrop,
                              ),
                            ),
                          ),
                        ),
                        icon: const Icon(Icons.auto_awesome_outlined),
                        label: const Text('Recommend rotations'),
                      ),
                    ],
                  ),
                ],
              ),
            ),
          ),
        ),
      ),
    );
  }
}
